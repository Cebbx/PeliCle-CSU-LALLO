<?php

namespace App\Http\Controllers;

use App\Models\ActivityLog;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\DB;
use Symfony\Component\HttpFoundation\StreamedResponse;

class BackupController extends Controller
{
    public function downloadBackup(Request $request): StreamedResponse|\Illuminate\Http\RedirectResponse
    {
        $admin = auth('admin')->user() ?? auth()->user();
        if (! $admin || ! in_array($admin->role, ['admin', 'super_admin'])) {
            abort(403, 'Unauthorized. Only system administrators can download database backups.');
        }

        try {
            ActivityLog::create([
                'user_id' => $admin->id,
                'user_name' => $admin->name ?? 'Admin',
                'action' => 'Downloaded Database Backup',
                'model_type' => 'Database',
                'model_id' => null,
                'details' => 'Admin downloaded full SQL database backup archive.',
                'ip_address' => $request->ip() ?? '127.0.0.1',
            ]);
        } catch (\Throwable $e) {}

        $timestamp = date('Y-m-d_H-i-s');
        $fileName = "pelicle_backup_{$timestamp}.sql";

        return response()->streamDownload(function () use ($admin, $timestamp) {
            $connection = config('database.default');

            echo "-- ========================================================\n";
            echo "-- PeliCle: CSU Lal-lo Vehicle & Trip Management System\n";
            echo "-- Automated Full SQL Database Backup\n";
            echo "-- Generated at: " . date('Y-m-d H:i:s') . "\n";
            echo "-- Generated by: " . ($admin->name ?? 'Admin') . " (" . ($admin->email ?? 'admin') . ")\n";
            echo "-- Connection: {$connection}\n";
            echo "-- ========================================================\n\n";

            if ($connection === 'mysql') {
                echo "SET FOREIGN_KEY_CHECKS=0;\n";
                echo "SET SQL_MODE = 'NO_AUTO_VALUE_ON_ZERO';\n";
                echo "SET time_zone = '+00:00';\n\n";

                $dbName = config('database.connections.mysql.database', 'pelicle');
                $tables = DB::select("SHOW TABLES FROM `{$dbName}`");
                $key = "Tables_in_{$dbName}";

                foreach ($tables as $t) {
                    $table = $t->$key ?? null;
                    if (! $table) continue;

                    echo "-- --------------------------------------------------------\n";
                    echo "-- Table structure and data for `{$table}`\n";
                    echo "-- --------------------------------------------------------\n";
                    echo "DROP TABLE IF EXISTS `{$table}`;\n";

                    $createRes = DB::select("SHOW CREATE TABLE `{$table}`");
                    $createSql = $createRes[0]->{'Create Table'} ?? '';
                    echo $createSql . ";\n\n";

                    $rows = DB::table($table)->get();
                    if ($rows->count() > 0) {
                        echo "-- Dumping data for table `{$table}` (" . $rows->count() . " rows)\n";
                        foreach ($rows as $row) {
                            $arr = (array) $row;
                            $cols = array_map(fn($c) => "`{$c}`", array_keys($arr));
                            $vals = array_map(function ($v) {
                                if (is_null($v)) return 'NULL';
                                return DB::getPdo()->quote((string) $v);
                            }, array_values($arr));

                            echo "INSERT INTO `{$table}` (" . implode(', ', $cols) . ") VALUES (" . implode(', ', $vals) . ");\n";
                        }
                        echo "\n";
                    }
                }

                echo "SET FOREIGN_KEY_CHECKS=1;\n";
                echo "-- Dump completed at " . date('Y-m-d H:i:s') . "\n";
            } else {
                // SQLite or other connection fallback
                $tables = DB::select("SELECT name, sql FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'");
                foreach ($tables as $t) {
                    $table = $t->name;
                    $createSql = $t->sql;

                    echo "-- Table structure and data for `{$table}`\n";
                    echo "DROP TABLE IF EXISTS `{$table}`;\n";
                    echo $createSql . ";\n\n";

                    $rows = DB::table($table)->get();
                    if ($rows->count() > 0) {
                        foreach ($rows as $row) {
                            $arr = (array) $row;
                            $cols = array_map(fn($c) => "`{$c}`", array_keys($arr));
                            $vals = array_map(function ($v) {
                                if (is_null($v)) return 'NULL';
                                return DB::getPdo()->quote((string) $v);
                            }, array_values($arr));

                            echo "INSERT INTO `{$table}` (" . implode(', ', $cols) . ") VALUES (" . implode(', ', $vals) . ");\n";
                        }
                        echo "\n";
                    }
                }
            }
        }, $fileName, [
            'Content-Type' => 'application/sql',
            'Content-Disposition' => "attachment; filename=\"{$fileName}\"",
            'Cache-Control' => 'no-cache, no-store, must-revalidate',
            'Pragma' => 'no-cache',
            'Expires' => '0',
        ]);
    }
}
